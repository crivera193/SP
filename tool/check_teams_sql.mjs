  await db.exec('set role authenticated');
  await actor(null);
  await assert.rejects(rpc('read'), /authenticated UTRGV/);
  await actor(3);
  await assert.rejects(rpc('choose', ['art_stuff']), /authenticated UTRGV/);
  await actor(1);
  assert.equal((await rpc('read')).team, null);
  assert.equal((await rpc('read')).choices.length, 3);
  await assert.rejects(rpc('choose', ['unknown']), /unavailable/);
  await assert.rejects(rpc('choose', [null]), /unavailable/);
